  required=[p for p in o['queries'] if p.get('required')]
  if required:lines.append('        Objects.requireNonNull(query, "query is required");')
  for p in required:lines.append('        Objects.requireNonNull(query.'+camel(p['name'])+', '+json.dumps(p['name']+' is required')+');')
