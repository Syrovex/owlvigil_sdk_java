(out/'GeneratedManagementClient.java').write_text('\n'.join(lines)+'\n')
(ROOT/'src/main/resources/com/owlvigil/management/operations.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(f'Generated {len(ops)} operations and {len(models)} models')
