  code=next(c for c in op['responses'] if c.startswith('2'))
  response=op['responses'][code].get('schema',{}).get('properties',{}).get('data')
  rt=typ(response,prefix+'Response') if response else 'Void'
  if rt.startswith('List<'):
   models[prefix+'Response']=('array',rt);rt=prefix+'Response'
  if rt.startswith('Map<'):
   models[prefix+'Response']=('map',rt);rt=prefix+'Response'
  bt=typ(body['schema'],prefix+'Request') if body else None
  ops.append(dict(name=name,prefix=prefix,method=method.upper(),path=path,paths=paths,queries=queries,qname=qname,body=body,bt=bt,rt=rt))
