  for p in o['queries']:
   n='query.'+camel(p['name']);lines.append('            '+('' if p.get('required') else 'if ('+n+' != null) ')+'path = appendQuery(path, '+json.dumps(p['name'])+', '+(n+'.value()' if p.get('enum') else n)+');')
