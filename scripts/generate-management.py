def pascal(s):return ''.join(x[:1].upper()+x[1:] for x in re.split(r'[^A-Za-z0-9]+',s) if x)
def camel(s):
 s=pascal(s);return s[:1].lower()+s[1:]+('Value' if s in ['Default','Class','Enum','Transient','Interface','Package','Public','Private','Protected','Native'] else '')
def model_name(k):
 if '.List_' in k:return model_name(k.split('.List_',1)[1].rstrip('_'))+'List'
 if '_modules_' in k:k=k.split('_modules_',1)[1]
 elif '_httpapi.' in k:k='Common.'+k.split('_httpapi.',1)[1]
 return pascal(k)
names={k:model_name(k) for k in spec['definitions']}
assert len(set(names.values()))==len(names),'model naming collision'
models={}
def typ(s,name):
 if '$ref' in s:return names[s['$ref'].split('/')[-1]]
 t=s.get('type')
 if s.get('enum'):
  if name not in models:models[name]=('enum',s)
  return name
 if t=='array':return 'List<'+typ(s['items'],name+'Item')+'>'
 if t=='integer':return 'Long'
 if t=='number':return 'Double'
 if t=='boolean':return 'Boolean'
 if t=='string':return 'String'
 if s.get('properties'):
  models.setdefault(name,('object',s));return name
 ap=s.get('additionalProperties')
 if isinstance(ap,dict):return 'Map<String, '+typ(ap,name+'Value')+'>'
 return 'JsonNode'
for k,s in spec['definitions'].items():models[names[k]]=('object',s)
ops=[]
for path,methods in sorted(spec['paths'].items()):
 for method,op in sorted(methods.items()):
  if method not in ['get','post','put','patch','delete']:continue
  name=camel(op['operationId']);prefix=pascal(op['operationId']);params=op.get('parameters',[])
