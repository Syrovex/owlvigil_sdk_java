 for p in o['paths']:
  n=camel(p['name']);lines.append('        Objects.requireNonNull('+n+', '+json.dumps(n+' is required')+');')
  if p['type']=='string':lines.append('        requireNonBlank('+n+', '+json.dumps(n)+');')
  lines.append('        path = path.replace('+json.dumps('{'+p['name']+'}')+', encode(String.valueOf('+n+')));')
